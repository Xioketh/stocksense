from datetime import datetime

from sqlalchemy import CheckConstraint, DateTime, ForeignKey, Integer, String, func
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db import Base
from app.services.stock_rules import is_low_stock


class Product(Base):
    __tablename__ = "products"
    __table_args__ = (
        CheckConstraint("qty >= 0", name="ck_products_qty_non_negative"),
        CheckConstraint("low_stock_threshold >= 0", name="ck_products_threshold_non_negative"),
    )

    id: Mapped[int] = mapped_column(primary_key=True)
    sku: Mapped[str] = mapped_column(String(64), unique=True, index=True)
    name: Mapped[str] = mapped_column(String(200))
    qty: Mapped[int] = mapped_column(Integer, default=0)
    low_stock_threshold: Mapped[int] = mapped_column(Integer, default=0)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())

    movements: Mapped[list["StockMovement"]] = relationship(back_populates="product")

    @property
    def is_low_stock(self) -> bool:
        return is_low_stock(self.qty, self.low_stock_threshold)


class StockMovement(Base):
    """Every stock change is recorded here (an audit trail).

    products.qty is the current value; stock_movements explains how we got there.
    """

    __tablename__ = "stock_movements"
    __table_args__ = (
        CheckConstraint("reason IN ('sale', 'invoice', 'adjustment')", name="ck_movements_reason"),
        # An 'invoice' movement MUST point to its invoice; other reasons must NOT.
        # (true = true or false = false -> OK; anything else -> rejected by Postgres)
        CheckConstraint(
            "(reason = 'invoice') = (invoice_id IS NOT NULL)", name="ck_movements_invoice_link"
        ),
    )

    id: Mapped[int] = mapped_column(primary_key=True)
    product_id: Mapped[int] = mapped_column(ForeignKey("products.id"), index=True)
    change: Mapped[int] = mapped_column(Integer)  # negative for sales, positive for invoices
    reason: Mapped[str] = mapped_column(String(20))
    invoice_id: Mapped[int | None] = mapped_column(ForeignKey("invoices.id"), index=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())

    product: Mapped[Product] = relationship(back_populates="movements")


class Invoice(Base):
    """One uploaded supplier invoice (PDF or photo) and its processing status.

    Status flow:
      pending_upload -> uploaded -> processing -> processed
                                             \\-> failed
    pending_upload: we gave out a signed URL, but the file isn't in the bucket yet.
    uploaded:       the worker saw the file arrive (Phase 3).
    processing / processed / failed: Gemini extraction (Phase 4).
    """

    __tablename__ = "invoices"
    __table_args__ = (
        CheckConstraint(
            "status IN ('pending_upload', 'uploaded', 'processing', 'processed', 'failed')",
            name="ck_invoices_status",
        ),
    )

    id: Mapped[int] = mapped_column(primary_key=True)
    # Object name inside the invoices bucket, e.g. "invoices/3f2a...e1.pdf".
    # Generated by the server, unique, and how the worker finds this row.
    gcs_path: Mapped[str] = mapped_column(String(300), unique=True, index=True)
    original_filename: Mapped[str] = mapped_column(String(255))  # for display only
    content_type: Mapped[str] = mapped_column(String(100))
    status: Mapped[str] = mapped_column(String(20), default="pending_upload", index=True)
    error_message: Mapped[str | None] = mapped_column(String(500))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    uploaded_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    processed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    items: Mapped[list["InvoiceItem"]] = relationship(
        back_populates="invoice", order_by="InvoiceItem.id"
    )


class InvoiceItem(Base):
    """One line the AI read from an invoice (filled by the worker in Phase 4)."""

    __tablename__ = "invoice_items"
    __table_args__ = (
        CheckConstraint("qty > 0", name="ck_invoice_items_qty_positive"),
        CheckConstraint("status IN ('matched', 'needs_review')", name="ck_invoice_items_status"),
        # 'matched' items must point to a product; 'needs_review' items must not.
        CheckConstraint(
            "(status = 'matched') = (matched_product_id IS NOT NULL)",
            name="ck_invoice_items_match_link",
        ),
    )

    id: Mapped[int] = mapped_column(primary_key=True)
    invoice_id: Mapped[int] = mapped_column(ForeignKey("invoices.id"), index=True)
    raw_name: Mapped[str] = mapped_column(String(200))  # exactly what the invoice said
    qty: Mapped[int] = mapped_column(Integer)
    matched_product_id: Mapped[int | None] = mapped_column(ForeignKey("products.id"))
    status: Mapped[str] = mapped_column(String(20))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())

    invoice: Mapped[Invoice] = relationship(back_populates="items")
